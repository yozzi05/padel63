// Рейтинг лиги: реальные данные с padelclub63.ru.
// На сайте клуба таблицы «Лига C» и «Зима» сейчас совпадают, поэтому массив один.
// Игроки с равными очками делят место.

export interface RatingRow {
  place: number;
  name: string;
  points: number;
}

const RAW = `
1 Березин 54 · 1 Бородина 54 · 1 Дербилова 54 · 2 Мельниченко 50 · 3 Обгольц 48
4 Намазов 44 · 5 Курушов 42 · 6 Рябцев 36 · 7 Файрушин 30 · 7 Александров 30
8 Оганезов 28 · 9 Голенков 26 · 9 Песьяков 26 · 10 Курдин 24 · 10 Канипов 24
11 Усачёв 22 · 11 Султанов 22 · 12 Киргизова 16 · 13 Абаимова 14 · 14 Егоров 12
14 Серый 12 · 15 Гольцев 10 · 16 Витюгов 4 · 16 Якуба 4 · 16 Бибаев 4
16 Курмакаев 4 · 17 Семененко 2 · 17 Минигулов 2 · 17 Кураев 2 · 17 Собиров 2
17 Ольхов 2 · 17 Шубин 2 · 17 Малкина 2 · 17 Тысячнов 2 · 17 Калачёв 2
17 Кузнецов 2 · 17 Куприянов 2 · 17 Файнер 2 · 17 Сильнов 2 · 17 Егорова 2
`;

const ROWS: RatingRow[] = RAW.split(/[·\n]/)
  .map((s) => s.trim())
  .filter(Boolean)
  .map((s) => {
    const [place, name, points] = s.split(/\s+/);
    return { place: Number(place), name, points: Number(points) };
  });

export const LEAGUES = [
  { id: "c", label: "Лига C", rows: ROWS },
  { id: "winter", label: "Зима", rows: ROWS },
] as const;

export type LeagueId = (typeof LEAGUES)[number]["id"];
